"""Generate db/migrations/0068_schema_comments.sql from mcp_server/schema_docs.py.

The droplet's MCP server served these docs through get_schema_docs(). With
Claude reading Supabase directly, they live on the tables and columns as
COMMENTs instead, where every schema listing shows them.

    python scripts/gen_schema_comments.py
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "db/migrations/0068_schema_comments.sql"

CUTOVER = (
    "Since 2026-10-23 (Whoop retired, Apple Watch in) the Whoop-only columns -- recovery_score, strain, "
    "day_kilojoules, sleep_performance_pct, sleep_consistency_pct, journal habits -- are NULL for new days; "
    "calendar and spending columns stopped with Google Calendar and Copilot. refresh_marts() rewrites the "
    "last 60 days of the training/sleep/nutrition/body/metric columns hourly."
)

HEADER = """-- 0068_schema_comments.sql
--
-- The droplet MCP server's hand-written schema docs (mcp_server/schema_docs.py),
-- moved onto the tables and columns themselves so the Supabase connector sees
-- them in every schema listing. Generated by scripts/gen_schema_comments.py;
-- regenerate rather than editing by hand.
--
-- comment_if_exists() skips anything the docs describe that no longer exists,
-- so the migration applies cleanly against any vintage of the schema.

CREATE OR REPLACE FUNCTION pg_temp.comment_if_exists(p_table text, p_column text, p_text text)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE kind "char";
BEGIN
  SELECT c.relkind INTO kind FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relname = p_table;
  IF kind IS NULL THEN RETURN; END IF;
  IF p_column IS NULL THEN
    EXECUTE format('COMMENT ON %s public.%I IS %L',
                   CASE kind WHEN 'v' THEN 'VIEW' WHEN 'm' THEN 'MATERIALIZED VIEW' ELSE 'TABLE' END, p_table, p_text);
  ELSIF EXISTS (SELECT 1 FROM information_schema.columns
                 WHERE table_schema = 'public' AND table_name = p_table AND column_name = p_column) THEN
    EXECUTE format('COMMENT ON COLUMN public.%I.%I IS %L', p_table, p_column, p_text);
  END IF;
END
$$;
"""


def _load_docs() -> dict:
    spec = importlib.util.spec_from_file_location("schema_docs", ROOT / "mcp_server/schema_docs.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.SCHEMA_DOCS


def _text(v) -> str:
    if isinstance(v, str):
        return v
    if isinstance(v, list):
        return " ".join(_text(x) for x in v)
    if isinstance(v, dict):
        return " ".join(f"{k}: {_text(x)}." for k, x in v.items())
    return str(v)


def _lit(s: str) -> str:
    return "$c$" + s.replace("$c$", "") + "$c$"


def main() -> None:
    docs = _load_docs()
    lines = [HEADER]
    for name, t in docs["tables"].items():
        body = f"{t['purpose']} Grain: {t['grain']}."
        if t.get("gotchas"):
            body += " Gotchas: " + _text(t["gotchas"])
        if name == "mart_daily":
            body = f"{CUTOVER} {body}"
        lines.append(f"SELECT pg_temp.comment_if_exists('{name}', NULL, {_lit(body)});")
        for key, desc in (t.get("columns") or {}).items():
            # Some entries document several columns at once: "a, b" or "zone_0..zone_5".
            for col in (c.strip() for c in key.split(",")):
                if ".." not in col:
                    lines.append(f"SELECT pg_temp.comment_if_exists('{name}', '{col}', {_lit(_text(desc))});")
    unified = docs["unified_layer"]
    for section in ("tables", "views"):
        for name, desc in unified.get(section, {}).items():
            if name not in docs["tables"]:
                lines.append(f"SELECT pg_temp.comment_if_exists('{name}', NULL, {_lit(_text(desc))});")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(lines) - 1} comments")


if __name__ == "__main__":
    main()
